import { ChangeDetectionStrategy, Component, inject } from '@angular/core';
import { CurrencyPipe, DatePipe } from '@angular/common';
import { MAT_DIALOG_DATA, MatDialogModule } from '@angular/material/dialog';
import { MatButtonModule } from '@angular/material/button';
import { MatIconModule } from '@angular/material/icon';
import { Order } from '@core/models';

/** Printable invoice preview. Uses the browser print dialog (Save as PDF) – no backend needed. */
@Component({
  selector: 'app-invoice-dialog',
  imports: [CurrencyPipe, DatePipe, MatDialogModule, MatButtonModule, MatIconModule],
  template: `
    <mat-dialog-content>
      <div class="invoice" id="invoice">
        <header>
          <div>
            <div class="logo">Shop<span>Sphere</span></div>
            <small>221 Commerce Way, Austin, TX · support&#64;shopsphere.dev</small>
          </div>
          <div class="meta">
            <h2>INVOICE</h2>
            <span>#INV-{{ order.number }}</span>
            <span>{{ order.createdAt | date: 'mediumDate' }}</span>
          </div>
        </header>
        <div class="parties">
          <div>
            <h4>Billed to</h4>
            <p>{{ order.customer.firstName }} {{ order.customer.lastName }}<br />{{ order.customer.email }}<br />{{ order.customer.phone }}</p>
          </div>
          <div>
            <h4>Ship to</h4>
            <p>{{ order.shippingAddress.fullName }}<br />{{ order.shippingAddress.line1 }}<br />{{ order.shippingAddress.city }}, {{ order.shippingAddress.state }} {{ order.shippingAddress.postalCode }}<br />{{ order.shippingAddress.country }}</p>
          </div>
        </div>
        <table>
          <thead><tr><th>Item</th><th>Qty</th><th>Unit</th><th>Amount</th></tr></thead>
          <tbody>
            @for (i of order.items; track i.productId) {
              <tr><td>{{ i.name }}</td><td>{{ i.quantity }}</td><td>{{ i.price | currency: 'USD' }}</td><td>{{ i.price * i.quantity | currency: 'USD' }}</td></tr>
            }
          </tbody>
        </table>
        <div class="totals">
          <div><span>Subtotal</span><span>{{ order.subtotal | currency: 'USD' }}</span></div>
          @if (order.discount) { <div><span>Discount</span><span>−{{ order.discount | currency: 'USD' }}</span></div> }
          <div><span>Shipping ({{ order.delivery.label }})</span><span>{{ order.shipping | currency: 'USD' }}</span></div>
          <div><span>Tax</span><span>{{ order.tax | currency: 'USD' }}</span></div>
          <div class="grand"><span>Total</span><span>{{ order.total | currency: 'USD' }}</span></div>
        </div>
        <footer>DEMO INVOICE – generated by a portfolio project. Not a tax document; no payment was collected.</footer>
      </div>
    </mat-dialog-content>
    <mat-dialog-actions align="end" class="no-print">
      <button mat-button mat-dialog-close type="button">Close</button>
      <button mat-flat-button type="button" (click)="print()"><mat-icon>print</mat-icon> Print / Save PDF</button>
    </mat-dialog-actions>
  `,
  styles: `
    .invoice { padding: 8px; color: #1c2333; font-size: 14px; }
    header { display: flex; justify-content: space-between; align-items: flex-start; border-bottom: 2px solid #14213d; padding-bottom: 14px; }
    .logo { font-family: var(--ss-font-display); font-weight: 800; font-size: 1.5rem; } .logo span { color: var(--ss-coral-strong); }
    .meta { text-align: right; display: flex; flex-direction: column; } .meta h2 { margin: 0; letter-spacing: 0.2em; }
    .parties { display: grid; grid-template-columns: 1fr 1fr; gap: 16px; margin: 16px 0; } h4 { margin: 0 0 4px; font-size: 12px; text-transform: uppercase; letter-spacing: 0.1em; color: #667085; } p { margin: 0; }
    table { width: 100%; border-collapse: collapse; } th, td { text-align: left; padding: 8px; border-bottom: 1px solid #e8e1d6; } th { background: #f3eee6; font-size: 12px; text-transform: uppercase; }
    td:not(:first-child), th:not(:first-child) { text-align: right; }
    .totals { margin-left: auto; width: min(320px, 100%); margin-top: 12px; } .totals div { display: flex; justify-content: space-between; padding: 4px 0; }
    .grand { font-weight: 800; font-size: 1.1rem; border-top: 2px solid #14213d; margin-top: 6px; padding-top: 8px !important; }
    footer { margin-top: 20px; font-size: 11px; color: #667085; text-align: center; }
  `,
  changeDetection: ChangeDetectionStrategy.OnPush,
})
export class InvoiceDialogComponent {
  readonly order = inject<Order>(MAT_DIALOG_DATA);

  print(): void {
    // Global print styles (styles.scss) hide the app behind the dialog while this class is set.
    document.body.classList.add('print-invoice');
    window.print();
    document.body.classList.remove('print-invoice');
  }
}
